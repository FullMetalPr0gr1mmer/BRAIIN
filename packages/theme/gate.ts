import pairs from './pairs.json';
import { contrast, fromHsl, mix, normalizeColour, toHsl } from './colour';
import {
  DEFAULT_COLORS,
  DEFAULT_SKY_SOFT,
  THEME_ROLES,
  generatePalette,
  isDefaultColors,
  type ThemeColors,
  type ThemeRole,
} from './palette';

// The theme's contrast gate (Admin v2 E4, AV-27; ui.md "Theme"): every pair a theme colour
// takes part in, on the site and in the admin (pairs.json), must meet WCAG 2.2 AA (4.5:1 for
// text, 3:1 for large text and non-text marks), or the theme is refused. The editor runs it as
// the person types, the Worker on every save and publish (the resource's schema), and the
// database again in a CHECK (the same pairs, generated by ./sql.ts). A refusal names the pair
// in words and, where one exists, a colour that passes: the nearest lightness of the same hue.

type Suite = 'site' | 'admin';
type Name = string;
type ColourDef = string | [Name, number, Name];
interface Block {
  colors: Record<Name, ColourDef>;
  words: Record<Name, string>;
  pairs: [Name, Name, number, string][];
}

const BLOCKS = { site: pairs.site, admin: pairs.admin } as unknown as Record<Suite, Block>;

/** The colours a palette resolves to: the three roles and the derived tint, lower case. */
export interface Palette extends ThemeColors {
  skySoft: string;
}

export interface PairFailure {
  suite: Suite;
  fg: Name;
  bg: Name;
  ratio: number;
  min: number;
  /** "White text on Hover is 3.2:1, needs 4.5:1 (white text on a hovered button)." */
  message: string;
  /** The roles this pair's two colours are made of. */
  roles: ThemeRole[];
}

export interface GateResult {
  ok: boolean;
  failures: PairFailure[];
  /** Per role named by a failure: the nearest colour of its hue whose own pairs all pass. */
  suggestions: Partial<Record<ThemeRole, string>>;
}

const lower = (colors: Readonly<ThemeColors>): ThemeColors => {
  const out = {} as ThemeColors;
  for (const role of THEME_ROLES) {
    const hex = normalizeColour(colors[role]);
    if (!hex) throw new Error(`${role} is not a colour: ${String(colors[role])}`);
    out[role] = hex.toLowerCase();
  }
  return out;
};

function resolver(block: Block, palette: Palette) {
  const memo = new Map<Name, string>();
  const resolve = (name: Name, depth = 0): string => {
    const hit = memo.get(name);
    if (hit) return hit;
    if (depth > 6) throw new Error(`pairs.json: ${name} nests too deep`);
    const def = block.colors[name];
    if (def === undefined) throw new Error(`pairs.json: no colour ${name}`);
    let hex: string;
    if (Array.isArray(def)) hex = mix(resolve(def[0], depth + 1), def[1], resolve(def[2], depth + 1));
    else if (def.startsWith('#')) hex = def.toLowerCase();
    else if (def === 'skySoft' || (THEME_ROLES as readonly string[]).includes(def))
      hex = palette[def as keyof Palette];
    else throw new Error(`pairs.json: ${name} is ${def}`);
    memo.set(name, hex);
    return hex;
  };
  return resolve;
}

/** The roles a colour of a block is made of (the derived tint counts as all three). */
function rolesOf(block: Block, name: Name, depth = 0): Set<ThemeRole> {
  const def = block.colors[name];
  const out = new Set<ThemeRole>();
  if (def === undefined || depth > 6) return out;
  if (Array.isArray(def)) {
    for (const r of rolesOf(block, def[0], depth + 1)) out.add(r);
    for (const r of rolesOf(block, def[2], depth + 1)) out.add(r);
  } else if (def === 'skySoft') THEME_ROLES.forEach((r) => out.add(r));
  else if ((THEME_ROLES as readonly string[]).includes(def)) out.add(def as ThemeRole);
  return out;
}

/** The ratio as the audit writes it: one decimal, floored (4.47 never reads "4.5:1"). */
export function ratioText(ratio: number): string {
  return `${(Math.floor(ratio * 10) / 10).toFixed(1)}:1`;
}

const capital = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** Every pair below its threshold, for a palette whose tint is already decided. */
function failuresOf(palette: Palette): PairFailure[] {
  const out: PairFailure[] = [];
  for (const suite of ['site', 'admin'] as const) {
    const block = BLOCKS[suite];
    const resolve = resolver(block, palette);
    for (const [fg, bg, min, where] of block.pairs) {
      const ratio = contrast(resolve(fg), resolve(bg));
      if (ratio >= min) continue;
      const roles = new Set([...rolesOf(block, fg), ...rolesOf(block, bg)]);
      out.push({
        suite,
        fg,
        bg,
        ratio,
        min,
        roles: THEME_ROLES.filter((r) => roles.has(r)),
        message: `${capital(block.words[fg] ?? fg)} on ${block.words[bg] ?? bg} is ${ratioText(ratio)}, needs ${ratioText(min)} (${where}).`,
      });
    }
  }
  return out;
}

/**
 * The light accent tint for a palette: global.css's own while the colours are the brand's,
 * else the accent mixed toward white just enough for every pair the tint is in to pass (white,
 * if none does: the gate then names the pair).
 */
export function skySoftFor(colors: Readonly<ThemeColors>): string {
  if (isDefaultColors(colors)) return DEFAULT_SKY_SOFT.toLowerCase();
  const base = lower(colors);
  const block = BLOCKS.site;
  const own = block.pairs.filter(([fg, bg]) => fg === 'skySoft' || bg === 'skySoft');
  const tintAt = (step: number) => mix('#ffffff', step / 50, base.accent);
  const passes = (step: number) => {
    const resolve = resolver(block, { ...base, skySoft: tintAt(step) });
    return own.every(([fg, bg, min]) => contrast(resolve(fg), resolve(bg)) >= min);
  };
  // The tint's grounds are dark (it is the light text on them), so a whiter tint only gains:
  // the first passing step is found by halving, then checked; the linear walk is the fallback.
  let lo = 0;
  let hi = 50;
  if (passes(hi)) {
    while (lo < hi) {
      const mid = Math.floor((lo + hi) / 2);
      if (passes(mid)) hi = mid;
      else lo = mid + 1;
    }
    if (lo === 0 || !passes(lo - 1)) return tintAt(lo);
  }
  for (let step = 0; step <= 50; step++) if (passes(step)) return tintAt(step);
  return '#ffffff';
}

/** The three colours and the derived tint, lower case. */
export function paletteOf(colors: Readonly<ThemeColors>): Palette {
  return { ...lower(colors), skySoft: skySoftFor(colors) };
}

/** Every failing pair for these colours (none: the theme passes). */
export function failuresFor(colors: Readonly<ThemeColors>): PairFailure[] {
  return failuresOf(paletteOf(colors));
}

/**
 * The nearest colour of `role`'s hue and saturation (its lightness moved up or down, the
 * smaller move first) with which every pair this colour takes part in passes, the other
 * colours as they are, upper case; null when no lightness does. A pair of two failing colours
 * is fixed by either; one the other colour alone fails stays the other's to fix, so two
 * suggestions taken together make the theme pass where each alone could not.
 */
export function suggestFor(colors: Readonly<ThemeColors>, role: ThemeRole): string | null {
  const [h, s, l] = toHsl(lower(colors)[role]);
  const mine = (c: Readonly<ThemeColors>) => failuresFor(c).filter((f) => f.roles.includes(role));
  for (let delta = 1; delta <= 100; delta += 1) {
    for (const dir of [-1, 1]) {
      const light = l + dir * delta;
      if (light < 0 || light > 100) continue;
      const candidate = fromHsl(h, s, light).toUpperCase();
      if (mine({ ...colors, [role]: candidate }).length === 0) return candidate;
    }
  }
  return null;
}

/** The gate: failures, and a suggestion for each role a failure names. */
export function gate(colors: Readonly<ThemeColors>): GateResult {
  const failures = failuresFor(colors);
  const suggestions: Partial<Record<ThemeRole, string>> = {};
  if (failures.length > 0) {
    const named = new Set(failures.flatMap((f) => f.roles));
    for (const role of THEME_ROLES) {
      if (!named.has(role)) continue;
      const pick = suggestFor(colors, role);
      if (pick) suggestions[role] = pick;
    }
  }
  return { ok: failures.length === 0, failures, suggestions };
}

/**
 * Moves the colours in `adjustable` (generated ones, never one the person chose) to their
 * suggestion, one at a time in order, until the palette passes or nothing more helps.
 */
export function settle(
  colors: Readonly<ThemeColors>,
  adjustable: readonly ThemeRole[],
): ThemeColors {
  let out: ThemeColors = { ...colors };
  for (let round = 0; round < adjustable.length + 1; round++) {
    const failures = failuresFor(out);
    if (failures.length === 0) return out;
    let moved = false;
    for (const role of adjustable) {
      if (!failures.some((f) => f.roles.includes(role))) continue;
      const pick = suggestFor(out, role);
      if (pick && pick !== out[role]) {
        out = { ...out, [role]: pick };
        moved = true;
        break;
      }
    }
    if (!moved) return out;
  }
  return out;
}

/**
 * Simple mode in full: the palette generated from one colour, its hover and accent settled.
 * The result may still fail (a main colour too light for white text): gate it.
 */
export function simplePalette(primary: string): ThemeColors {
  // The brand's own primary makes the brand's own palette (hover and accent as designed).
  if (normalizeColour(primary) === normalizeColour(DEFAULT_COLORS.primary)) {
    return { ...DEFAULT_COLORS };
  }
  return settle(generatePalette(primary), ['hover', 'accent']);
}

/**
 * Simple mode's suggestion for the main colour itself: the nearest lightness of its hue whose
 * settled palette passes; null when none does.
 */
export function suggestMain(primary: string): string | null {
  const main = normalizeColour(primary);
  if (!main) return null;
  const [h, s, l] = toHsl(main);
  // Two points of lightness a step: each candidate settles a whole palette, so this is the
  // slow one (the editor runs it only on a failure, after typing stops).
  for (let delta = 2; delta <= 100; delta += 2) {
    for (const dir of [-1, 1]) {
      const light = l + dir * delta;
      if (light < 0 || light > 100) continue;
      const candidate = fromHsl(h, s, light).toUpperCase();
      if (failuresFor(simplePalette(candidate)).length === 0) return candidate;
    }
  }
  return null;
}
