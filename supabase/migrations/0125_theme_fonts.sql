-- ═══ Postconditions ════════════════════════════════════════════════════════════════════════
do $$
declare
  v_bad text;
  v1 jsonb := '{"v":1,"mode":"simple","colors":{"primary":"#0024BC","hover":"#024CFF","accent":"#22A9FF"},"motion":{"marquee":"normal","reveal":true}}';
  v2 jsonb;
  v3 jsonb;
begin
  v2 := v1 || '{"v":2,"shapes":{"corners":"brand","buttons":"pill"},"type":{"headingWeight":800,"headingCase":"uppercase"}}';
  v3 := v2 || '{"v":3,"fonts":{"latin":"archivo","arabic":"almarai"}}';
  -- ---- 1. v1 and v2 as E12 held them; v3 at the brand's fonts with no font token -----------
  if not app.theme_row_ok(v1, '{}') or not app.theme_row_ok(v2, '{}')
     or not app.theme_row_ok(v3, '{}')
     or not app.theme_row_ok(jsonb_set(v3, '{shapes,corners}', '"square"'), '{"--bs-radius-scale":"0"}')
     or not app.theme_row_ok(jsonb_set(v2, '{type,headingWeight}', '700'), '{"--bs-heading-weight":"700"}') then
    raise exception 'E13: a v1, v2 or v3 theme at the brand''s fonts is refused';
  end if;
  if app.theme_row_ok(v3 - 'fonts', '{}')
     or app.theme_row_ok(v2 || '{"fonts":{"latin":"archivo","arabic":"almarai"}}', '{}')
     or app.theme_row_ok(v1 || '{"fonts":{"latin":"archivo","arabic":"almarai"}}', '{}')
     or app.theme_row_ok(jsonb_set(v3, '{v}', '4'), '{}')
     or app.theme_row_ok(v3 #- '{fonts,arabic}', '{}')
     or app.theme_row_ok(jsonb_set(v3, '{fonts,extra}', '"x"'), '{}')
     or app.theme_row_ok(jsonb_set(v3, '{fonts,latin}', '"inter"'), '{}')
     or app.theme_row_ok(jsonb_set(v3, '{fonts,arabic}', '"archivo"'), '{}')
     or app.theme_row_ok(jsonb_set(v3, '{fonts,latin}', '1'), '{}')
     or app.theme_row_ok(v3, jsonb_build_object('--bs-font-sans',
          '''Archivo'', ''Archivo Fallback'', system-ui, -apple-system, ''Segoe UI'', Roboto, sans-serif'))
     or app.theme_row_ok(v3, '{"--bs-font-ar":"serif"}')
     or app.theme_row_ok(v3, '{"--bs-font-sans":""}')
     or app.theme_row_ok(v2, '{"--bs-font-sans":"serif"}')
     or app.theme_row_ok(v1, '{"--bs-font-ar":"serif"}') then
    raise exception 'E13: app.theme_row_ok does not hold the v3 fonts or the font tokens';
  end if;
  if has_function_privilege('anon', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or has_function_privilege('public', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or not has_function_privilege('authenticated', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or not has_function_privilege('service_role', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or (select p.prosecdef or p.provolatile <> 'i' or p.proconfig is distinct from array['search_path=""']
           from pg_proc p where p.oid = 'app.theme_row_ok(jsonb, jsonb)'::regprocedure) then
    raise exception 'E13: app.theme_row_ok must be invoker, immutable, search_path pinned, executable by authenticated and service_role only';
  end if;

  -- ---- 2. the CHECK still calls it, and every row there is passes it ---------------------
  if not exists (select 1 from pg_constraint
                  where conrelid = 'public.custom_themes'::regclass
                    and conname = 'custom_themes_theme_v1' and contype = 'c' and convalidated
                    and pg_get_constraintdef(oid) ~ 'theme_row_ok\(settings, tokens\)') then
    raise exception 'E13: custom_themes_theme_v1 is missing, unvalidated or not as written';
  end if;
  select string_agg(id::text, ', ') into v_bad
    from public.custom_themes where not app.theme_row_ok(settings, tokens);
  if v_bad is not null then
    raise exception 'E13: themes that no longer pass the rules: %', v_bad;
  end if;

  -- ---- 3. the guide ---------------------------------------------------------------------
  if not exists (select 1 from app.help_guide_catalog
                  where slug = 'theme' and revision = 3 and sort_order = 97
                    and body::text like '%"Fonts"%'
                    and body::text not like '%the fonts are fixed%') then
    raise exception 'E13: the catalog must hold theme at revision 3 with the Fonts card';
  end if;
  select string_agg(t.id::text, ', ') into v_bad
    from public.tenants t
   where not exists (select 1 from public.help_articles h
                      where h.tenant_id = t.id and h.slug = 'theme'
                        and h.body::text like '%"Fonts"%');
  if v_bad is not null then
    raise exception 'E13: tenants without the new theme guide: %', v_bad;
  end if;
  if exists (select 1 from app.release_tenants) then
    raise exception 'E13: releases must stay off (app.release_tenants is not empty)';
  end if;
end $$;
