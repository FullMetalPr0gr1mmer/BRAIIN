-- ═══ 1. app.theme_row_ok: v1 or v2 ═════════════════════════════════════════════════════════
-- A row's settings and tokens (true for a legacy row: no settings). Never raises on a bad
-- value: every shape is checked before anything reads it. Invoker, immutable, empty search
-- path, as E4 created it (CREATE OR REPLACE keeps the grants; the settings are restated).
create or replace function app.theme_row_ok(p_settings jsonb, p_tokens jsonb) returns boolean
  language plpgsql immutable parallel safe set search_path = ''
as $$
declare
  v_colors jsonb;
  v_motion jsonb;
  v_shapes jsonb;
  v_type jsonb;
  v_v2 boolean;
  v_default boolean;
  v_scale text;
  v_colour_keys constant text[] := array['--bs-klein', '--bs-cobalt', '--bs-sky', '--bs-sky-soft',
    '--bs-glow-klein', '--bs-glow-sky', '--bs-shadow-klein', '--bs-shadow-cobalt'];
  v_shape_keys constant text[] := array['--bs-radius-scale', '--bs-btn-radius',
    '--bs-heading-weight', '--bs-heading-case'];
  v_present int;
begin
  if p_settings is null then
    return true;
  end if;
  -- The settings: exactly {v: 1, mode, colors, motion} (E4) or {v: 2, mode, colors, motion,
  -- shapes, type} (E12).
  if jsonb_typeof(p_settings) is distinct from 'object' then
    return false;
  end if;
  if p_settings -> 'v' = '1'::jsonb then
    v_v2 := false;
    if (select array_agg(k order by k collate "C") from jsonb_object_keys(p_settings) k)
       is distinct from array['colors', 'mode', 'motion', 'v'] then
      return false;
    end if;
  elsif p_settings -> 'v' = '2'::jsonb then
    v_v2 := true;
    if (select array_agg(k order by k collate "C") from jsonb_object_keys(p_settings) k)
       is distinct from array['colors', 'mode', 'motion', 'shapes', 'type', 'v'] then
      return false;
    end if;
  else
    return false;
  end if;
  if jsonb_typeof(p_settings -> 'mode') is distinct from 'string'
     or (p_settings ->> 'mode') not in ('simple', 'advanced') then
    return false;
  end if;
  v_colors := p_settings -> 'colors';
  v_motion := p_settings -> 'motion';
  if jsonb_typeof(v_colors) is distinct from 'object'
     or (select array_agg(k order by k collate "C") from jsonb_object_keys(v_colors) k)
        is distinct from array['accent', 'hover', 'primary']
     or exists (select 1 from jsonb_each(v_colors) e(k, v)
                 where jsonb_typeof(e.v) <> 'string' or (e.v #>> '{}') !~ '^#[0-9A-F]{6}$') then
    return false;
  end if;
  if jsonb_typeof(v_motion) is distinct from 'object'
     or (select array_agg(k order by k collate "C") from jsonb_object_keys(v_motion) k)
        is distinct from array['marquee', 'reveal']
     or jsonb_typeof(v_motion -> 'marquee') is distinct from 'string'
     or (v_motion ->> 'marquee') not in ('normal', 'slower', 'slowest')
     or jsonb_typeof(v_motion -> 'reveal') is distinct from 'boolean' then
    return false;
  end if;
  if v_v2 then
    v_shapes := p_settings -> 'shapes';
    v_type := p_settings -> 'type';
    if jsonb_typeof(v_shapes) is distinct from 'object'
       or (select array_agg(k order by k collate "C") from jsonb_object_keys(v_shapes) k)
          is distinct from array['buttons', 'corners']
       or jsonb_typeof(v_type) is distinct from 'object'
       or (select array_agg(k order by k collate "C") from jsonb_object_keys(v_type) k)
          is distinct from array['headingCase', 'headingWeight'] then
      return false;
    end if;
  end if;

  -- The tokens: an object of the closed key set, each value a string of its key's shape.
  if jsonb_typeof(p_tokens) is distinct from 'object' then
    return false;
  end if;
  if exists (
    select 1
      from jsonb_each(p_tokens) as t(k, v)
      left join (values
    -- BEGIN theme token rules
    ('--bs-klein', '^#[0-9a-f]{6}$'),
    ('--bs-cobalt', '^#[0-9a-f]{6}$'),
    ('--bs-sky', '^#[0-9a-f]{6}$'),
    ('--bs-sky-soft', '^#[0-9a-f]{6}$'),
    ('--bs-glow-klein', '^rgba\([0-9]{1,3}, [0-9]{1,3}, [0-9]{1,3}, 0\.[0-9]{1,2}\)$'),
    ('--bs-glow-sky', '^rgba\([0-9]{1,3}, [0-9]{1,3}, [0-9]{1,3}, 0\.[0-9]{1,2}\)$'),
    ('--bs-shadow-klein', '^0 [0-9]{1,2}px [0-9]{1,2}px rgba\([0-9]{1,3}, [0-9]{1,3}, [0-9]{1,3}, 0\.[0-9]{1,2}\)$'),
    ('--bs-shadow-cobalt', '^0 [0-9]{1,2}px [0-9]{1,2}px rgba\([0-9]{1,3}, [0-9]{1,3}, [0-9]{1,3}, 0\.[0-9]{1,2}\)$'),
    ('--bs-marquee-scale', '^(1\.5|2\.5)$'),
    ('--bs-rv-from', '^1$'),
    ('--bs-rv-shift', '^0px$'),
    ('--bs-radius-scale', '^(0|0\.5|1\.5)$'),
    ('--bs-btn-radius', '^(10px|0px)$'),
    ('--bs-heading-weight', '^700$'),
    ('--bs-heading-case', '^none$')
    -- END theme token rules
      ) as r(name, pattern) on r.name = t.k
     where r.name is null or jsonb_typeof(t.v) <> 'string' or (t.v #>> '{}') !~ r.pattern) then
    return false;
  end if;

  -- Motion: exactly what the settings say, and nothing that adds motion.
  v_scale := case v_motion ->> 'marquee' when 'slower' then '1.5' when 'slowest' then '2.5' end;
  if (p_tokens ->> '--bs-marquee-scale') is distinct from v_scale
     or (p_tokens ? '--bs-rv-from') is distinct from ((v_motion ->> 'reveal') = 'false')
     or (p_tokens ? '--bs-rv-shift') is distinct from ((v_motion ->> 'reveal') = 'false') then
    return false;
  end if;

  -- Shapes and type: a v1 theme writes none of their tokens; a v2 theme's every setting is one
  -- of its choices (of its JSON type), and its token exactly what that choice writes (none for
  -- the brand's).
  if not v_v2 then
    if p_tokens ?| v_shape_keys then
      return false;
    end if;
  elsif exists (
    with s(grp, key, kind, choice, token, value) as (values
    -- BEGIN theme shape rules
    ('shapes', 'corners', 'string', 'brand', '--bs-radius-scale', null::text),
    ('shapes', 'corners', 'string', 'square', '--bs-radius-scale', '0'),
    ('shapes', 'corners', 'string', 'soft', '--bs-radius-scale', '0.5'),
    ('shapes', 'corners', 'string', 'round', '--bs-radius-scale', '1.5'),
    ('shapes', 'buttons', 'string', 'pill', '--bs-btn-radius', null::text),
    ('shapes', 'buttons', 'string', 'rounded', '--bs-btn-radius', '10px'),
    ('shapes', 'buttons', 'string', 'square', '--bs-btn-radius', '0px'),
    ('type', 'headingWeight', 'number', '800', '--bs-heading-weight', null::text),
    ('type', 'headingWeight', 'number', '700', '--bs-heading-weight', '700'),
    ('type', 'headingCase', 'string', 'uppercase', '--bs-heading-case', null::text),
    ('type', 'headingCase', 'string', 'as-written', '--bs-heading-case', 'none')
    -- END theme shape rules
    )
    select 1
      from (select distinct grp, key from s) as k
     where not exists (
       select 1 from s as r
        where r.grp = k.grp and r.key = k.key
          and jsonb_typeof(p_settings -> r.grp -> r.key) = r.kind
          and (p_settings -> r.grp ->> r.key) = r.choice
          and (p_tokens ->> r.token) is not distinct from r.value)) then
    return false;
  end if;

  -- Colours: none while the colours are the brand's, all eight otherwise, the three named
  -- ones equal to the settings, every glow and shadow the compiler's own string (a glow is a
  -- ground under text), and every pair passing (E4, unchanged).
  select bool_and(upper(v_colors ->> d.role) = d.hex) into v_default
    from (values
    -- BEGIN theme defaults
    ('primary', '#0024BC'),
    ('hover', '#024CFF'),
    ('accent', '#22A9FF')
    -- END theme defaults
    ) as d(role, hex);
  select count(*) into v_present from unnest(v_colour_keys) as k where p_tokens ? k;
  if v_default then
    return v_present = 0;
  end if;
  return v_present = 8
     and p_tokens ->> '--bs-klein' = lower(v_colors ->> 'primary')
     and p_tokens ->> '--bs-cobalt' = lower(v_colors ->> 'hover')
     and p_tokens ->> '--bs-sky' = lower(v_colors ->> 'accent')
     and not exists (
       select 1
         from (values
    -- BEGIN theme effects
    ('--bs-glow-klein', '', 'primary', '0.42'),
    ('--bs-glow-sky', '', 'accent', '0.45'),
    ('--bs-shadow-klein', '0 12px 38px ', 'primary', '0.45'),
    ('--bs-shadow-cobalt', '0 18px 48px ', 'hover', '0.45')
    -- END theme effects
         ) as e(token, prefix, role, alpha)
        where (p_tokens ->> e.token) is distinct from
              e.prefix || app.theme_rgba(v_colors ->> e.role, e.alpha))
     and app.theme_palette_ok(p_tokens ->> '--bs-klein', p_tokens ->> '--bs-cobalt',
                              p_tokens ->> '--bs-sky', p_tokens ->> '--bs-sky-soft');
end $$;

