-- ═══ Postconditions ════════════════════════════════════════════════════════════════════════
do $$
declare
  v_bad text;
  v1 jsonb := '{"v":1,"mode":"simple","colors":{"primary":"#0024BC","hover":"#024CFF","accent":"#22A9FF"},"motion":{"marquee":"normal","reveal":true}}';
  v2 jsonb;
begin
  v2 := v1 || '{"v":2,"shapes":{"corners":"brand","buttons":"pill"},"type":{"headingWeight":800,"headingCase":"uppercase"}}';
  -- ---- 1. v1 as E4 held it; v2 at the brand's with no token; each choice's own token ------
  if not app.theme_row_ok(v1, '{}') or not app.theme_row_ok(v2, '{}') then
    raise exception 'E12: the brand defaults with no token are refused (v1 or v2)';
  end if;
  if app.theme_row_ok(v1, '{"--bs-radius-scale":"0"}')
     or app.theme_row_ok(v1 || '{"shapes":{"corners":"brand","buttons":"pill"}}', '{}')
     or app.theme_row_ok(v2 - 'type', '{}')
     or app.theme_row_ok(jsonb_set(v2, '{v}', '3'), '{}')
     or app.theme_row_ok(v2, '{"--bs-radius-scale":"0"}')
     or app.theme_row_ok(v2, '{"--bs-radius-scale":"1"}')
     or app.theme_row_ok(jsonb_set(v2, '{shapes,corners}', '"square"'), '{}')
     or app.theme_row_ok(jsonb_set(v2, '{shapes,corners}', '"square"'), '{"--bs-radius-scale":"0.5"}')
     or app.theme_row_ok(jsonb_set(v2, '{shapes,corners}', '"huge"'), '{}')
     or app.theme_row_ok(jsonb_set(v2, '{type,headingWeight}', '"700"'), '{"--bs-heading-weight":"700"}')
     or app.theme_row_ok(jsonb_set(v2, '{type,headingWeight}', '900'), '{}')
     or app.theme_row_ok(jsonb_set(v2, '{shapes,extra}', '1'), '{}')
     or app.theme_row_ok(v2, '{"--bs-btn-radius":"3px"}') then
    raise exception 'E12: app.theme_row_ok does not hold the v1 and v2 shapes';
  end if;
  if not app.theme_row_ok(
       jsonb_set(jsonb_set(jsonb_set(jsonb_set(v2, '{shapes,corners}', '"square"'),
         '{shapes,buttons}', '"rounded"'), '{type,headingWeight}', '700'),
         '{type,headingCase}', '"as-written"'),
       '{"--bs-radius-scale":"0","--bs-btn-radius":"10px","--bs-heading-weight":"700","--bs-heading-case":"none"}')
     or not app.theme_row_ok(jsonb_set(v2, '{shapes,corners}', '"round"'), '{"--bs-radius-scale":"1.5"}')
     or not app.theme_row_ok(jsonb_set(v2, '{shapes,buttons}', '"square"'), '{"--bs-btn-radius":"0px"}') then
    raise exception 'E12: a v2 theme with its shape and type tokens is refused';
  end if;
  if has_function_privilege('anon', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or has_function_privilege('public', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or not has_function_privilege('authenticated', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or not has_function_privilege('service_role', 'app.theme_row_ok(jsonb, jsonb)', 'execute')
     or (select p.prosecdef or p.provolatile <> 'i' or p.proconfig is distinct from array['search_path=""']
           from pg_proc p where p.oid = 'app.theme_row_ok(jsonb, jsonb)'::regprocedure) then
    raise exception 'E12: app.theme_row_ok must be invoker, immutable, search_path pinned, executable by authenticated and service_role only';
  end if;

  -- ---- 2. the CHECK still calls it, and every row there is passes it ---------------------
  if not exists (select 1 from pg_constraint
                  where conrelid = 'public.custom_themes'::regclass
                    and conname = 'custom_themes_theme_v1' and contype = 'c' and convalidated
                    and pg_get_constraintdef(oid) ~ 'theme_row_ok\(settings, tokens\)') then
    raise exception 'E12: custom_themes_theme_v1 is missing, unvalidated or not as written';
  end if;
  select string_agg(id::text, ', ') into v_bad
    from public.custom_themes where not app.theme_row_ok(settings, tokens);
  if v_bad is not null then
    raise exception 'E12: themes that no longer pass the rules: %', v_bad;
  end if;

  -- ---- 3. the guide ---------------------------------------------------------------------
  if not exists (select 1 from app.help_guide_catalog
                  where slug = 'theme' and revision = 2 and sort_order = 97
                    and body::text like '%Shapes and type%'
                    and body::text not like '%the shapes are fixed%') then
    raise exception 'E12: the catalog must hold theme at revision 2 with the Shapes and type cards';
  end if;
  select string_agg(t.id::text, ', ') into v_bad
    from public.tenants t
   where not exists (select 1 from public.help_articles h
                      where h.tenant_id = t.id and h.slug = 'theme'
                        and h.body::text like '%Shapes and type%');
  if v_bad is not null then
    raise exception 'E12: tenants without the new theme guide: %', v_bad;
  end if;
  if exists (select 1 from app.release_tenants) then
    raise exception 'E12: releases must stay off (app.release_tenants is not empty)';
  end if;
end $$;
