-- ═══ 6. The live check on every staff write ════════════════════════════════════════════════
-- Since this slice a theme restyles the live site and the whole admin, so its writes take the
-- profile, read now, not only the token (app.live_role(), 0033: null for a profile that is
-- inactive, locked, in another tenant or not the token's role). RESTRICTIVE: ANDed with
-- 0001's custom_themes_write and 0038's custom_themes_delete_admin, so it can only narrow.
-- Not FOR ALL: reads stay open to every CMS role (the releases preview, see the header). The
-- service role and the definer functions (apply_release) are not `authenticated`, so none of
-- these applies to them. `(select ...)` makes the profile read one InitPlan per statement.
-- The helper's canonical definition, search_path pinned (E4 code review CR8): any later
-- migration that creates it again (E5 does) repeats these three lines byte for byte, which
-- tests/lib/themeSql.spec.ts holds.
create or replace function app.role_edits_theme(r text) returns boolean
  language sql immutable
  set search_path = ''
as $$ select coalesce(r in ('admin', 'developer'), false) $$;  -- theme.edit
revoke all on function app.role_edits_theme(text) from public, anon, authenticated, service_role;
grant execute on function app.role_edits_theme(text) to authenticated, service_role;

drop policy if exists custom_themes_live_insert on public.custom_themes;
create policy custom_themes_live_insert on public.custom_themes as restrictive for insert to authenticated
  with check (tenant_id = app.effective_tenant_id() and app.role_edits_theme((select app.live_role())));
drop policy if exists custom_themes_live_update on public.custom_themes;
create policy custom_themes_live_update on public.custom_themes as restrictive for update to authenticated
  using (tenant_id = app.effective_tenant_id() and app.role_edits_theme((select app.live_role())))
  with check (tenant_id = app.effective_tenant_id() and app.role_edits_theme((select app.live_role())));
drop policy if exists custom_themes_live_delete on public.custom_themes;
create policy custom_themes_live_delete on public.custom_themes as restrictive for delete to authenticated
  using (tenant_id = app.effective_tenant_id() and app.role_edits_theme((select app.live_role())));

