-- Relative luminance of `#rrggbb` (WCAG 2.2).
create or replace function app.theme_luminance(p_hex text) returns double precision
  language sql immutable strict parallel safe set search_path = ''
as $$
  select sum(c.w * case when c.s <= 0.03928 then c.s / 12.92
                        else pg_catalog.power((c.s + 0.055) / 1.055, 2.4) end)
    from (values
      ((('x' || pg_catalog.substr(p_hex, 2, 2))::bit(8)::int)::float8 / 255.0, 0.2126::float8),
      ((('x' || pg_catalog.substr(p_hex, 4, 2))::bit(8)::int)::float8 / 255.0, 0.7152::float8),
      ((('x' || pg_catalog.substr(p_hex, 6, 2))::bit(8)::int)::float8 / 255.0, 0.0722::float8)
    ) as c(s, w)
$$;

-- `p_top` painted at p_k hundredths over `p_under`: whole numbers, rounded half up, as
-- packages/theme/colour.ts mix() computes it (lower-case `#rrggbb`).
create or replace function app.theme_mix(p_top text, p_k int, p_under text) returns text
  language sql immutable strict parallel safe set search_path = ''
as $$
  select '#' || string_agg(
           pg_catalog.lpad(pg_catalog.to_hex(
             (t.a * p_k + t.b * (100 - p_k) + 50) / 100), 2, '0'), '' order by t.at)
    from (select x.at,
                 ('x' || pg_catalog.substr(p_top, x.at, 2))::bit(8)::int as a,
                 ('x' || pg_catalog.substr(p_under, x.at, 2))::bit(8)::int as b
            from (values (2), (4), (6)) as x(at)) as t
$$;

-- `#rrggbb` at an alpha, as packages/theme/compile.ts writes it in a glow or a shadow:
-- `rgba(r, g, b, alpha)`, the channels in decimal.
create or replace function app.theme_rgba(p_hex text, p_alpha text) returns text
  language sql immutable strict parallel safe set search_path = ''
as $$
  select 'rgba(' || string_agg(
           (('x' || pg_catalog.substr(p_hex, x.at, 2))::bit(8)::int)::text, ', ' order by x.at)
         || ', ' || p_alpha || ')'
    from (values (2), (4), (6)) as x(at)
$$;

-- The contrast ratio of two colours, 1 to 21.
create or replace function app.theme_contrast(p_a text, p_b text) returns double precision
  language sql immutable strict parallel safe set search_path = ''
as $$
  select (greatest(l.a, l.b) + 0.05) / (least(l.a, l.b) + 0.05)
    from (select app.theme_luminance(p_a) as a, app.theme_luminance(p_b) as b) as l
$$;

