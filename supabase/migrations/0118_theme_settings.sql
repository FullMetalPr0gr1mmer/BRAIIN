declare
  v_bad text;
  v_got text[];
  v_ok_tokens jsonb;
  v_settings jsonb;
  r text;
begin
  -- ---- 1. the rules: defaults pass, a failing palette and a wrong shape do not ------------
  if not app.theme_palette_ok('#0024bc', '#024cff', '#22a9ff', '#9ed4ff') then
    raise exception 'E4: the brand defaults fail the theme pairs';
  end if;
  if app.theme_palette_ok('#0024bc', '#7fb2ff', '#22a9ff', '#9ed4ff') then
    raise exception 'E4: a light hover (white text on it is about 2.3:1) passes the theme pairs';
  end if;
  if app.theme_mix('#ffffff', 80, '#0024bc') <> '#ccd3f2'
     or app.theme_mix('#ffffff', 70, '#0024bc') <> '#b3bdeb'
     or app.theme_rgba('#0024BC', '0.42') <> 'rgba(0, 36, 188, 0.42)'
     or abs(app.theme_contrast('#ffffff', '#000000') - 21) > 1e-9 then
    raise exception 'E4: the colour maths do not give the expected values';
  end if;
  v_settings := '{"v":1,"mode":"simple","colors":{"primary":"#0024BC","hover":"#024CFF","accent":"#22A9FF"},"motion":{"marquee":"normal","reveal":true}}';
  if not app.theme_row_ok(v_settings, '{}') then
    raise exception 'E4: the brand defaults with no token are refused';
  end if;
  if app.theme_row_ok(v_settings, '{"--bs-klein":"#0024bc"}')
     or app.theme_row_ok(v_settings, '{"--x":"red"}')
     or app.theme_row_ok(v_settings, '{"--bs-marquee-scale":"0.5"}')
     or app.theme_row_ok(v_settings || '{"extra":1}', '{}')
     or app.theme_row_ok(jsonb_set(v_settings, '{motion,reveal}', '"no"'), '{}')
     or not app.theme_row_ok(null, '{"--anything":"goes; } on a legacy row"}') then
    raise exception 'E4: app.theme_row_ok does not hold the v1 shape';
  end if;
  v_ok_tokens := '{"--bs-rv-from":"1","--bs-rv-shift":"0px","--bs-marquee-scale":"2.5"}';
  if not app.theme_row_ok(jsonb_set(jsonb_set(v_settings, '{motion,reveal}', 'false'),
                                    '{motion,marquee}', '"slowest"'), v_ok_tokens) then
    raise exception 'E4: reduced motion with its tokens is refused';
  end if;
  foreach r in array array['app.theme_luminance(text)', 'app.theme_mix(text, int, text)',
                           'app.theme_contrast(text, text)', 'app.theme_rgba(text, text)',
                           'app.theme_palette_ok(text, text, text, text)',
                           'app.theme_row_ok(jsonb, jsonb)'] loop
    if has_function_privilege('anon', r, 'execute')
       or has_function_privilege('public', r, 'execute')
       or not has_function_privilege('authenticated', r, 'execute')
       or not has_function_privilege('service_role', r, 'execute') then
      raise exception 'E4: % must be executable by authenticated and service_role only', r;
    end if;
    if (select p.prosecdef or p.provolatile <> 'i' or p.proconfig is distinct from array['search_path=""']
          from pg_proc p where p.oid = r::regprocedure) then
      raise exception 'E4: % must be invoker, immutable, search_path pinned', r;
    end if;
