       'custom_themes_delete_admin:DELETE:RESTRICTIVE:{public}',
       'custom_themes_live_delete:DELETE:RESTRICTIVE:{authenticated}',
       'custom_themes_live_insert:INSERT:RESTRICTIVE:{authenticated}',
       'custom_themes_live_update:UPDATE:RESTRICTIVE:{authenticated}',
       'custom_themes_public_read:SELECT:PERMISSIVE:{anon}',
       'custom_themes_read:SELECT:PERMISSIVE:{public}',
       'custom_themes_write:ALL:PERMISSIVE:{public}'] then
    raise exception 'E4: the custom_themes policies are %', v_got;
  end if;
