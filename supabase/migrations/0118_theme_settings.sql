  select string_agg(policyname, ', ' order by policyname) into v_bad
    from pg_policies
   where schemaname = 'public' and tablename = 'custom_themes'
     and policyname in ('custom_themes_live_insert', 'custom_themes_live_update',
                        'custom_themes_live_delete')
     and exists (select 1 from unnest(array[qual, with_check]) as c(x)
                  where c.x is not null
                    and c.x !~ '^\(\(tenant_id = app\.effective_tenant_id\(\)\) AND app\.role_edits_theme\(\( SELECT app\.live_role\(\)');
  if v_bad is not null then
    raise exception 'E4: the live policies % are not the tenant fence and the live theme.edit check', v_bad;
  end if;
  if not exists (select 1 from pg_proc
                  where oid = 'app.role_edits_theme(text)'::regprocedure
                    and provolatile = 'i' and not prosecdef
                    and proconfig = array['search_path=""']
                    and prosrc ~ 'r in \(''admin'', ''developer''\)')
     or has_function_privilege('anon', 'app.role_edits_theme(text)', 'execute')
     or has_function_privilege('public', 'app.role_edits_theme(text)', 'execute')
     or not has_function_privilege('authenticated', 'app.role_edits_theme(text)', 'execute') then
    raise exception 'E4: app.role_edits_theme must be an immutable Admin + Developer check, search_path pinned, executable by staff and the service role only';
  end if;
  if not exists (select 1 from pg_policies
                  where schemaname = 'public' and tablename = 'custom_themes'
                    and policyname = 'custom_themes_public_read'
                    and qual ~ '^\(\(tenant_id = app\.effective_tenant_id\(\)\)'
                    and qual ~ 'is_active' and qual ~ 'settings IS NOT NULL') then
    raise exception 'E4: custom_themes_public_read is not the tenant fence first, active, v1';
  end if;
  if has_table_privilege('anon', 'public.custom_themes', 'select')
     or not has_column_privilege('anon', 'public.custom_themes', 'tokens', 'select')
     or has_column_privilege('anon', 'public.custom_themes', 'version', 'select') then
    raise exception 'E4: anon must read custom_themes.tokens only, and no table privilege';
  end if;
  select string_agg(a.attname, ', ' order by a.attname) into v_bad
    from pg_attribute a
   where a.attrelid = 'public.custom_themes'::regclass and a.attnum > 0 and not a.attisdropped
     and a.attname <> 'tokens'
     and (has_column_privilege('anon', a.attrelid, a.attnum, 'select')
          or has_column_privilege('anon', a.attrelid, a.attnum, 'insert')
          or has_column_privilege('anon', a.attrelid, a.attnum, 'update')
          or has_column_privilege('anon', a.attrelid, a.attnum, 'references'));
  if v_bad is not null then
    raise exception 'E4: anon holds a privilege on custom_themes columns %', v_bad;
  end if;
  if has_any_column_privilege('anon', 'public.custom_themes', 'insert, update, references')
     or has_table_privilege('anon', 'public.custom_themes', 'insert, update, delete, truncate, references, trigger') then
    raise exception 'E4: anon holds a write privilege on custom_themes';
  end if;
  if not (has_table_privilege('authenticated', 'public.custom_themes', 'select')
          and has_table_privilege('authenticated', 'public.custom_themes', 'insert')
          and has_table_privilege('authenticated', 'public.custom_themes', 'update')
          and has_table_privilege('authenticated', 'public.custom_themes', 'delete')) then
    raise exception 'E4: authenticated lost one of 0011''s privileges on custom_themes';
  end if;
  foreach r in array array['public', 'anon', 'authenticated', 'service_role'] loop
    if has_table_privilege(r::name, 'public.custom_themes', 'truncate') then
      raise exception 'E4: % holds TRUNCATE on custom_themes (0066 revoked it)', r;
    end if;
  end loop;
  if not (select relrowsecurity and relforcerowsecurity from pg_class
           where oid = 'public.custom_themes'::regclass) then
    raise exception 'E4: public.custom_themes is not ENABLE + FORCE row level security';
  end if;

  -- ---- 4. the registry stages settings; the snapshot, capture and guard triggers stand ----
  select columns into v_got from app.release_entities where entity_type = 'custom_theme';
  if v_got is distinct from array['name', 'tokens', 'is_active', 'settings'] then
    raise exception 'E4: the custom_theme registry columns are %', v_got;
  end if;
  if not exists (select 1 from app.release_entities
                  where entity_type = 'custom_theme' and table_name = 'custom_themes'
                    and key_column = 'id' and area = 'appearance'
                    and author_roles = array['admin', 'developer']
                    and delete_roles = array['admin']
                    and deferred_columns = '{}' and unique_flags = '{}'
                    and exempt_columns = '{}' and apply_order = 110 and not has_status
                    and publish_flag is null) then
    raise exception 'E4: the custom_theme registry row moved beyond its columns';
  end if;
  select array_agg(t.tgname::text || ':' || p.proname::text order by t.tgname) into v_got
    from pg_trigger t join pg_proc p on p.oid = t.tgfoid
   where t.tgrelid = 'public.custom_themes'::regclass and not t.tgisinternal
     and t.tgenabled = 'O'
     and t.tgname in ('custom_themes_snapshot', 'custom_themes_release_capture',
                      'custom_themes__release_guard');
  if v_got is distinct from array['custom_themes__release_guard:tg_release_guard',
                                  'custom_themes_release_capture:tg_release_capture',
                                  'custom_themes_snapshot:tg_snapshot_version'] then
    raise exception 'E4: the custom_themes release triggers are %', v_got;
  end if;
  if exists (select 1 from app.release_tenants) then
    raise exception 'E4: releases must stay off (app.release_tenants is not empty)';
  end if;

  -- ---- 5. the guides --------------------------------------------------------------------
  if not exists (select 1 from app.help_guide_catalog
                  where slug = 'theme' and revision = 1 and sort_order = 97
                    and title = 'The site''s theme' and caps = array['theme.edit']
                    and screens = array['/admin/appearance/theme']) then
    raise exception 'E4: the catalog must hold theme at revision 1, place 97';
  end if;
  if (select count(*) from app.help_guide_catalog where sort_order = 97) <> 1 then
    raise exception 'E4: place 97 must hold one guide';
  end if;
  if not exists (select 1 from app.help_guide_catalog
                  where slug = 'roles-and-access' and revision = 4
                    and body::text not like '%do not change the site yet%'
                    and body::text like '%the site''s theme (its colours and motion)%') then
    raise exception 'E4: roles-and-access must be at revision 4 without "do not change the site yet"';
  end if;
  select string_agg(t.id::text, ', ') into v_bad
    from public.tenants t
   where not exists (select 1 from public.help_articles h
                      where h.tenant_id = t.id and h.slug = 'theme' and h.sort_order = 97)
      or exists (select 1 from public.help_articles h
                  where h.tenant_id = t.id and h.slug = 'roles-and-access'
                    and h.body::text like '%do not change the site yet%');
  if v_bad is not null then
    raise exception 'E4: tenants without the theme guide or with the old roles text: %', v_bad;
  end if;
  if has_function_privilege('anon', 'app.help_article_set()', 'execute')
     or has_function_privilege('authenticated', 'app.help_article_set()', 'execute')
     or has_function_privilege('service_role', 'app.help_article_set()', 'execute')
     or has_table_privilege('authenticated', 'app.help_guide_catalog', 'select')
     or has_table_privilege('anon', 'app.help_guide_catalog', 'select') then
    raise exception 'E4: an API role may read the help set or the catalog';
  end if;
end $$;
